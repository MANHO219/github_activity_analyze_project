"""Build a reviewed source-only tar and raw/LF hash manifest; never deploy it."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import tarfile

PROJECT = Path(__file__).resolve().parents[2]
sys.path.insert(0,str(PROJECT / "a_data_pipeline"))
from rolling_pipeline.batch_support import code_identity


def source_files():
    names = ["README.md","d_parallel_experiments/README.md","a_data_pipeline/README.md","a_data_pipeline/environment.yml",
             "a_data_pipeline/config/sample.json","a_data_pipeline/rolling_pipeline/README.md",
             "a_data_pipeline/rolling_pipeline/requirements.txt"]
    files = [PROJECT / name for name in names]
    for folder in ("a_data_pipeline/gharchive_a","a_data_pipeline/scripts","a_data_pipeline/rolling_pipeline",
                   "a_data_pipeline/tests","a_data_pipeline/rolling_pipeline/tests"):
        files.extend((PROJECT / folder).glob("*.py"))
    for name in ("run_batch_pipeline.py","spark_batch_job.py","verify_results.py","summarize_results.py","prepare_batch_deployment.py"):
        files.append(PROJECT / "d_parallel_experiments/scripts" / name)
    for name in ("local_1core.json","local_4core.json","distributed_4core.json"):
        files.append(PROJECT / "d_parallel_experiments/configs" / name)
    for name in ("monthly_pipeline.md","cluster_setup.md","local_validation.md","requirements_alignment_20261112.md"):
        files.append(PROJECT / "d_parallel_experiments/docs" / name)
    files.append(PROJECT / "d_parallel_experiments/tests/test_batch_pipeline.py")
    return sorted(set(files))


def prepare(archive_path,manifest_path):
    files = source_files()
    entries = {}
    for path in files:
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(PROJECT):
            raise ValueError(f"Missing or unsafe deployment source: {path}")
        raw = path.read_bytes()
        entries[path.relative_to(PROJECT).as_posix()] = {"bytes":len(raw),"sha256_raw":hashlib.sha256(raw).hexdigest(),
                                                        "sha256_lf":hashlib.sha256(raw.replace(b"\r\n",b"\n")).hexdigest()}
    value = {"format":"rolling-source-v1","runtime_identity":code_identity(),"files":entries,
             "excludes":"raw, runs, results, credentials, SSH handoff, logs, archives and generated bytecode"}
    manifest_path.parent.mkdir(parents=True,exist_ok=True)
    archive_path.parent.mkdir(parents=True,exist_ok=True)
    if manifest_path.exists() or archive_path.exists():
        raise FileExistsError("Deployment archive/manifest must use new names")
    with manifest_path.open("x",encoding="utf-8") as handle:
        handle.write(json.dumps(value,ensure_ascii=False,indent=2)+"\n")
    with tarfile.open(archive_path,"x:gz") as archive:
        for path in files:
            archive.add(path,arcname=path.relative_to(PROJECT).as_posix(),recursive=False)
        archive.add(manifest_path,arcname="DEPLOYMENT_SHA256.json",recursive=False)
    # Read every archived member and validate contents, not just tar headers.
    with tarfile.open(archive_path,"r:gz") as archive:
        if set(archive.getnames())!=set(entries)|{"DEPLOYMENT_SHA256.json"}:
            raise RuntimeError("Unexpected deployment archive members")
        for name,entry in entries.items():
            data = archive.extractfile(name).read()
            if len(data)!=entry["bytes"] or hashlib.sha256(data).hexdigest()!=entry["sha256_raw"]:
                raise RuntimeError(f"Archived source differs: {name}")
    return len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive",type=Path,required=True)
    parser.add_argument("--manifest",type=Path,required=True)
    args = parser.parse_args()
    print(json.dumps({"source_files":prepare(args.archive,args.manifest),"archive":str(args.archive)}))


if __name__=="__main__":
    main()
